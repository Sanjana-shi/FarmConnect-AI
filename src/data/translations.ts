export function getTranslated(lang: LanguageCode, key: string, fallback?: string): string {
  return TRANSLATIONS[lang]?.[key] || TRANSLATIONS.en?.[key] || fallback || key;
}

export function translateCrop(crop: string, lang: LanguageCode): string {
  const c = crop.toLowerCase();
  if (c.includes('paddy') || c.includes('rice')) return getTranslated(lang, 'paddy', 'Paddy');
  if (c.includes('sugarcane')) return getTranslated(lang, 'sugarcane', 'Sugarcane');
  if (c.includes('cotton')) return getTranslated(lang, 'cotton', 'Cotton');
  if (c.includes('banana')) return getTranslated(lang, 'banana', 'Banana');
  if (c.includes('wheat')) return getTranslated(lang, 'wheat', 'Wheat');
  if (c.includes('pulse')) return getTranslated(lang, 'pulses', 'Pulses');
  return crop;
}

export function translateWorkType(workType: string, lang: LanguageCode): string {
  const w = workType.toLowerCase();
  if (w.includes('harvest')) return getTranslated(lang, 'harvesting', 'Harvesting');
  if (w.includes('bundle') || w.includes('bundling')) return getTranslated(lang, 'bundling', 'Bundling');
  if (w.includes('cut') || w.includes('cutting')) return getTranslated(lang, 'cutting', 'Cutting');
  if (w.includes('weed') || w.includes('weeding')) return getTranslated(lang, 'weeding', 'Weeding');
  if (w.includes('sow') || w.includes('sowing')) return getTranslated(lang, 'sowing', 'Sowing');
  if (w.includes('transplant')) return getTranslated(lang, 'transplantation', 'Transplantation');
  if (w.includes('tractor')) return getTranslated(lang, 'tractor', 'Tractor Operation');
  return workType;
}

export function translateJobTitle(title: string, lang: LanguageCode): string {
  if (title === 'Paddy Harvesting & Bundling' || title === 'Paddy Harvesting & Threshing') {
    return `${getTranslated(lang, 'paddy', 'Paddy')} ${getTranslated(lang, 'harvesting', 'Harvesting')} & ${getTranslated(lang, 'bundling', 'Bundling')}`;
  }
  if (title === 'Sugarcane Cutting') {
    return `${getTranslated(lang, 'sugarcane', 'Sugarcane')} ${getTranslated(lang, 'cutting', 'Cutting')}`;
  }
  if (title.includes('Cotton')) {
    return `${getTranslated(lang, 'cotton', 'Cotton')} ${getTranslated(lang, 'weeding', 'Weeding')}`;
  }
  if (title.includes('Banana')) {
    return `${getTranslated(lang, 'banana', 'Banana')} ${getTranslated(lang, 'bananaPlantation', 'Plantation Care')}`;
  }
  return title;
}
