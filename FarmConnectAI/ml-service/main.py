@app.post("/ml/workforce-demand", response_model=DemandPredictionResponse)
def predict_workforce_demand(req: DemandPredictionRequest):
    crop = req.cropType.lower()
    work = req.workType.lower()
    month = req.month.lower() if req.month else "september"

    # Agro-climatic seasonal demand heuristic
    is_peak = False
    demand = "MODERATE"
    shortage = 35
    peak_period = f"{req.month} 10–25"
    action = "Post your job 3-5 days in advance to ensure full worker crew."

    if "paddy" in crop and ("harvest" in work or "transplant" in work):
        demand = "VERY_HIGH" if "sep" in month or "oct" in month or "nov" in month else "HIGH"
        shortage = 78 if demand == "VERY_HIGH" else 55
        peak_period = "September 10–22"
        action = "High labor competition anticipated across district. Post job immediately and offer standard ₹750-800 daily wage to lock in labor crew."
    elif "sugarcane" in crop:
        demand = "HIGH"
        shortage = 60
        peak_period = "November – January"
        action = "Heavy cane-cutting crew requirement. Book specialized teams in advance."

    return DemandPredictionResponse(
        district=req.district,
        cropType=req.cropType,
        workType=req.workType,
        demandLevel=demand,
        shortageRiskPercent=shortage,
        expectedPeakPeriod=peak_period,
        suggestedAction=action,
        confidenceScore=0.91,
        factors=[
            f"Regional harvesting calendar for {req.district}",
            f"Cropping pattern density of {req.cropType}",
            f"Monsoon cycle and field readiness metrics"
        ]
    )

# --- Feature 13: Workforce Cost Simulator ---
@app.post("/ml/workforce-cost", response_model=WorkforceCostResponse)
def calculate_workforce_cost(req: WorkforceCostRequest):
    total = float(req.numberOfWorkers * req.durationDays * req.dailyWage)
    lower = round(total * 0.92, 0)
    upper = round(total * 1.08, 0)

    breakdown = f"{req.numberOfWorkers} workers × {req.durationDays} days × ₹{int(req.dailyWage)}/day = ₹{int(total):,} INR"
    savings = None
    if req.numberOfWorkers > 10 and req.durationDays > 3:
        savings = "Tip: Forming a unified worker team of 10+ workers can save 5-8% on supervision and logistics overhead."

    return WorkforceCostResponse(
        workers=req.numberOfWorkers,
        durationDays=req.durationDays,
        dailyWage=req.dailyWage,
        estimatedTotal=total,
        lowerRange=lower,
        upperRange=upper,
        costBreakdownText=breakdown,
        savingsTip=savings
    )

# --- Feature 14: What-If AI Workforce Analysis ---
@app.post("/ml/workforce-scenario", response_model=ScenarioComparisonResponse)
def analyze_scenario(req: ScenarioComparisonRequest):
    current_cost = float(req.currentWorkers * req.currentDays * req.currentDailyWage)
    alt_cost = float(req.simulatedWorkers * req.simulatedDays * req.simulatedDailyWage)
    cost_diff = alt_cost - current_cost
    time_saved = req.currentDays - req.simulatedDays

    if time_saved > 0 and cost_diff <= 0:
        recommendation = "Highly Recommended: The alternative plan completes the harvest faster with equal or lower total expenditure."
    elif time_saved > 0:
        recommendation = f"Favorable Trade-off: Spending +₹{int(cost_diff):,} saves {time_saved} day(s), protecting mature crop from adverse weather risk."
    elif time_saved == 0:
        recommendation = "Neutral: Same completion duration. Review wage differences."
    else:
        recommendation = f"Caution: Alternative plan requires {abs(time_saved)} additional day(s)."

    trade_off = (
        f"Base Plan: {req.currentWorkers} workers for {req.currentDays} days = ₹{int(current_cost):,}. "
        f"Simulated: {req.simulatedWorkers} workers for {req.simulatedDays} days = ₹{int(alt_cost):,}. "
        f"Net difference: {'+' if cost_diff > 0 else ''}₹{int(cost_diff):,} & {time_saved} days saved."
    )

    return ScenarioComparisonResponse(
        currentPlanCost=current_cost,
        alternativePlanCost=alt_cost,
        costDifference=cost_diff,
        timeSavedDays=time_saved,
        aiRecommendation=recommendation,
        tradeOffSummary=trade_off
    )

