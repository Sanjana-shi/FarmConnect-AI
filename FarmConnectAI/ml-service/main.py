@app.post("/ml/team-recommendation", response_model=List[RecommendedTeamResult])
def recommend_teams(req: TeamRecommendationRequest):
    results = []
    for team in req.teams:
        dist = haversine_distance(req.latitude, req.longitude, team.latitude, team.longitude)
        size_diff = abs(team.memberCount - req.requiredTeamSize)
        size_score = max(40, 100 - (size_diff * 12))
        
        has_skill = any(req.workType.lower() in s.lower() or req.cropType.lower() in s.lower() for s in team.skills)
        skill_score = 100 if has_skill else 60
        dist_score = max(30, int(100 - (dist * 3.0)))
        rating_score = int((team.rating / 5.0) * 100)

        match = int((size_score * 0.35) + (skill_score * 0.30) + (dist_score * 0.20) + (rating_score * 0.15))
        match = min(99, max(45, match))

        reasons = [
            f"Team size of {team.memberCount} matches requirement ({req.requiredTeamSize} requested)",
            f"Located {dist} km from farm",
            f"Completed {team.completedTeamJobs} group farm contracts together"
        ]
        if has_skill:
            reasons.append(f"Specialized in {req.workType}")

        results.append(RecommendedTeamResult(
            teamId=team.teamId,
            teamName=team.teamName,
            leaderName=team.leaderName,
            memberCount=team.memberCount,
            matchScore=match,
            distanceKm=dist,
            reasons=reasons
        ))

    results.sort(key=lambda x: x.matchScore, reverse=True)
    return results

