@app.post("/ml/recommend-workers", response_model=List[RecommendedWorkerResult])
def recommend_workers(req: RecommendRequest):
    results = []
    job = req.job

    for worker in req.candidates:
        dist = haversine_distance(job.latitude, job.longitude, worker.latitude, worker.longitude)
        
        # Explainable Weighted Feature Scoring
        skill_match = 1.0 if any(job.workType.lower() in s.lower() for s in worker.skills) else 0.4
        dist_score = max(0.0, 1.0 - (dist / 50.0))
        exp_score = min(1.0, worker.experienceYears / 10.0)
        rating_score = worker.rating / 5.0
        reliability_weight = worker.reliabilityScore / 100.0

        total_score = (
            skill_match * 0.35 +
            dist_score * 0.25 +
            reliability_weight * 0.20 +
            rating_score * 0.10 +
            exp_score * 0.10
        ) * 100.0

        reasons = []
        if skill_match > 0.8:
            reasons.append(f"Expert in {job.workType}")
        if dist < 10.0:
            reasons.append(f"Nearby worker ({dist} km away)")
        if worker.reliabilityScore >= 90:
            reasons.append("High reliability track record")
        if worker.rating >= 4.5:
            reasons.append("Top rated by neighboring farmers")

        results.append(RecommendedWorkerResult(
            workerId=worker.workerId,
            fullName=worker.fullName,
            recommendationScore=round(total_score, 1),
            matchReasons=reasons,
            distanceKm=dist
        ))

    results.sort(key=lambda x: x.recommendationScore, reverse=True)
    return results

@app.post("/ml/predict-wage", response_model=WagePredictResponse)
def predict_wage(req: WagePredictRequest):
    base_rate = 650.0
    if "paddy" in req.cropType.lower() or "rice" in req.cropType.lower():
        base_rate += 100.0
    if "harvest" in req.workType.lower():
        base_rate += 120.0
    elif "sowing" in req.workType.lower() or "weeding" in req.workType.lower():
        base_rate += 50.0

    lower = round(base_rate * 0.90, 0)
    upper = round(base_rate * 1.10, 0)

    return WagePredictResponse(
        suggestedWagePerDay=base_rate,
        currency="INR",
        lowerRange=lower,
        upperRange=upper,
        confidenceScore=0.92,
        factors=[
            f"Crop category: {req.cropType}",
            f"Work type intensity: {req.workType}",
            f"Seasonal labor demand index for {req.district}"
        ]
    )

@app.post("/ml/reliability-score", response_model=ReliabilityScoreResponse)
def compute_reliability(req: ReliabilityScoreRequest):
    score = (
        (req.attendanceRate * 40.0) +
        ((req.averageRating / 5.0) * 30.0) +
        (min(1.0, req.completedJobs / 20.0) * 20.0) -
        (req.cancellations * 5.0) -
        (req.lateArrivals * 2.0)
    )
    final_score = int(max(10, min(100, score + 10)))
    category = "Exceptional" if final_score >= 90 else "Reliable" if final_score >= 75 else "Moderate"
    
    return ReliabilityScoreResponse(
        reliabilityScore=final_score,
        category=category,
        explanation=[
            f"Based on {req.completedJobs} verified completed jobs",
            f"On-time attendance rate: {int(req.attendanceRate * 100)}%",
            f"Average farmer rating: {req.averageRating} / 5.0"
        ]
    )

