@app.post("/ml/workforce-optimization", response_model=WorkforceOptimizationResponse)
def optimize_workforce(req: WorkforceOptimizationRequest):
    # Rule of thumb for labor throughput per acre
    crop_lower = req.cropType.lower()
    work_lower = req.workType.lower()
    
    labor_multiplier = 3.0
    duration = 2.5
    if "harvest" in work_lower:
        labor_multiplier = 3.0
        duration = max(1.5, req.farmSizeAcres * 0.5)
    elif "sowing" in work_lower or "transplant" in work_lower:
        labor_multiplier = 2.5
        duration = max(1.0, req.farmSizeAcres * 0.4)
    elif "weeding" in work_lower:
        labor_multiplier = 2.0
        duration = max(1.0, req.farmSizeAcres * 0.3)
    
    workers_needed = max(1, int(math.ceil(req.farmSizeAcres * labor_multiplier)))
    
    daily_wage = req.maxDailyWage if req.maxDailyWage and req.maxDailyWage > 0 else 750.0
    estimated_total = round(workers_needed * duration * daily_wage, 2)
    
    # Rank candidates non-discriminatorily purely based on skills, reliability, rating, distance, experience
    scored_candidates = []
    for c in req.candidates:
        dist = haversine_distance(req.latitude, req.longitude, c.latitude, c.longitude)
        has_skill = any(work_lower in s.lower() or crop_lower in s.lower() for s in c.skills)
        skill_score = 100 if has_skill else 55
        
        # Distance decay
        dist_score = max(30, int(100 - (dist * 3.5)))
        match_pct = int((skill_score * 0.40) + (c.reliabilityScore * 0.30) + ((c.rating / 5.0 * 100) * 0.15) + (dist_score * 0.15))
        match_pct = min(99, max(50, match_pct))
        
        reasons = []
        if has_skill:
            reasons.append(f"Verified {req.workType} experience")
        if dist <= 5.0:
            reasons.append(f"Very close to farm ({dist} km)")
        elif dist <= 15.0:
            reasons.append(f"Manageable transit distance ({dist} km)")
        if c.reliabilityScore >= 90:
            reasons.append("High reliability track record (90%+)")
        if c.rating >= 4.5:
            reasons.append("Top-rated performance by past farmers")
        if c.completedJobsCount >= 10:
            reasons.append(f"Completed {c.completedJobsCount}+ verified field shifts")

        scored_candidates.append(OptimizedWorkerItem(
            workerId=c.workerId,
            fullName=c.fullName,
            matchPercentage=match_pct,
            distanceKm=dist,
            reliabilityScore=c.reliabilityScore,
            rating=c.rating,
            dailyWage=daily_wage,
            explainableReasons=reasons[:4]
        ))

    scored_candidates.sort(key=lambda x: (x.matchPercentage, -x.distanceKm), reverse=True)
    selected_team = scored_candidates[:workers_needed]

    insights = [
        f"Optimal labor configuration: {workers_needed} workers for {req.farmSizeAcres} acres of {req.cropType} {req.workType}.",
        f"Estimated work duration is {duration} working days with good field conditions.",
        f"Projected total labor expenditure: ₹{int(estimated_total):,} INR at ₹{int(daily_wage)}/day per laborer."
    ]

    return WorkforceOptimizationResponse(
        cropType=req.cropType,
        farmSizeAcres=req.farmSizeAcres,
        workersRequired=workers_needed,
        recommendedWorkersCount=len(selected_team),
        estimatedDurationDays=duration,
        estimatedTotalCost=estimated_total,
        recommendedTeam=selected_team,
        planningInsights=insights
    )

